function loadServiceFromUrl() {
  const urlParams = new URLSearchParams(window.location.search);
  let requestedService = urlParams.get('service');

  if (!requestedService || !servicesDetailData[requestedService]) {
    
    requestedService = 'event-booking';
  }

  currentServiceId = requestedService;
  renderServiceDetail(currentServiceId);
}

